CREATE TABLE metric_counters (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version    BIGINT NOT NULL,
    scope_id   BIGINT NOT NULL,
    metric     VARCHAR(30) NOT NULL,
    day        DATE NOT NULL,
    value      BIGINT NOT NULL,
    CONSTRAINT uq_metric UNIQUE (scope_id, metric, day)
);
CREATE INDEX idx_metric_lookup ON metric_counters (scope_id, metric);

CREATE TABLE status_counters (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version    BIGINT NOT NULL,
    scope_id   BIGINT NOT NULL,
    status     VARCHAR(20) NOT NULL,
    value      BIGINT NOT NULL,
    CONSTRAINT uq_status UNIQUE (scope_id, status)
);

CREATE TABLE role_counters (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version    BIGINT NOT NULL,
    role       VARCHAR(20) NOT NULL,
    value      BIGINT NOT NULL
);
CREATE UNIQUE INDEX idx_role_counter ON role_counters (role);

CREATE TABLE job_counters (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version      BIGINT NOT NULL,
    job_id       BIGINT NOT NULL,
    company_id   BIGINT NOT NULL,
    job_title    VARCHAR(255),
    applications BIGINT NOT NULL
);
CREATE UNIQUE INDEX idx_jobcounter_job ON job_counters (job_id);
CREATE INDEX idx_jobcounter_company ON job_counters (company_id);
