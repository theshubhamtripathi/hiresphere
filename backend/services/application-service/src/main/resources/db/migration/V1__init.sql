CREATE TABLE job_applications (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version            BIGINT NOT NULL,
    job_id             BIGINT NOT NULL,
    applicant_id       BIGINT NOT NULL,
    company_id         BIGINT NOT NULL,
    resume_id          BIGINT,
    resume_snapshot    JSONB,
    cover_letter       TEXT,
    expected_salary    NUMERIC(15, 2),
    notice_period      VARCHAR(255),
    available_from     DATE,
    answers            JSONB,
    status             VARCHAR(20) NOT NULL,
    ai_match_score     INTEGER,
    ai_matched_skills  JSONB,
    ai_missing_skills  JSONB,
    ai_summary         TEXT,
    ai_recommendation  VARCHAR(255),
    CONSTRAINT uq_job_applicant UNIQUE (job_id, applicant_id)
);
CREATE INDEX idx_app_applicant ON job_applications (applicant_id);
CREATE INDEX idx_app_job ON job_applications (job_id);
CREATE INDEX idx_app_company ON job_applications (company_id);

CREATE TABLE application_notes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version        BIGINT NOT NULL,
    application_id BIGINT NOT NULL,
    author_id      BIGINT NOT NULL,
    content        TEXT NOT NULL
);
CREATE INDEX idx_note_application ON application_notes (application_id);

CREATE TABLE application_status_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version        BIGINT NOT NULL,
    application_id BIGINT NOT NULL,
    from_status    VARCHAR(20),
    to_status      VARCHAR(20) NOT NULL,
    changed_by     BIGINT,
    note           TEXT
);
CREATE INDEX idx_history_application ON application_status_history (application_id);
