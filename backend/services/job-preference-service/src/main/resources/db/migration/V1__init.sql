CREATE TABLE saved_jobs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version    BIGINT NOT NULL,
    user_id    BIGINT NOT NULL,
    job_id     BIGINT NOT NULL,
    CONSTRAINT uq_saved_job UNIQUE (user_id, job_id)
);
CREATE INDEX idx_saved_user ON saved_jobs (user_id);

CREATE TABLE job_preferences (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version         BIGINT NOT NULL,
    user_id         BIGINT NOT NULL,
    desired_titles  JSONB,
    locations       JSONB,
    job_types       JSONB,
    work_modes      JSONB,
    min_salary      NUMERIC(15, 2),
    category_ids    JSONB,
    skills          JSONB,
    alerts_enabled  BOOLEAN NOT NULL,
    alert_frequency VARCHAR(20)
);
CREATE UNIQUE INDEX idx_pref_user ON job_preferences (user_id);
