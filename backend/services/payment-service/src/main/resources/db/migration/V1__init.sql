CREATE TABLE plans (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version           BIGINT NOT NULL,
    code              VARCHAR(20) NOT NULL,
    name              VARCHAR(255) NOT NULL,
    price_inr         NUMERIC(12, 2) NOT NULL,
    job_credits       INTEGER NOT NULL,
    featured_listings INTEGER NOT NULL,
    description       TEXT
);
CREATE UNIQUE INDEX idx_plan_code ON plans (code);

CREATE TABLE subscriptions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version      BIGINT NOT NULL,
    company_id   BIGINT NOT NULL,
    plan_code    VARCHAR(20) NOT NULL,
    status       VARCHAR(20) NOT NULL,
    valid_until  TIMESTAMP(6) WITH TIME ZONE,
    credits_left INTEGER NOT NULL
);
CREATE UNIQUE INDEX idx_sub_company ON subscriptions (company_id);

CREATE TABLE payment_orders (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version             BIGINT NOT NULL,
    company_id          BIGINT NOT NULL,
    plan_code           VARCHAR(20) NOT NULL,
    razorpay_order_id   VARCHAR(255) NOT NULL,
    amount              NUMERIC(12, 2) NOT NULL,
    currency            VARCHAR(3) NOT NULL,
    status              VARCHAR(20) NOT NULL,
    razorpay_payment_id VARCHAR(255)
);
CREATE UNIQUE INDEX idx_order_razorpay ON payment_orders (razorpay_order_id);
CREATE INDEX idx_order_company ON payment_orders (company_id);

